#!/usr/bin/env ruby
# frozen_string_literal: true

# Regenerates Ruflet::UI::ServiceTypes::ENGINE_SERVICE_TYPES from the Flutter
# engine: every `case "Wire":` label inside a `createService` method in
# packages/ruflet/lib and packages/ruflet_*/lib of a ruflet-engine checkout.
#
#   ruby tools/sync_engine_service_types.rb --engine ../ruflet-engine
#   ruby tools/sync_engine_service_types.rb --engine ../ruflet-engine --check
#
# --engine defaults to $RUFLET_ENGINE_ROOT, then to a sibling ../ruflet-engine.

require "optparse"

ROOT = File.expand_path("..", __dir__)
TARGET = File.join(ROOT, "packages/ruflet_core/lib/ruflet_ui/ruflet/ui/service_types.rb")
BEGIN_MARKER = "# BEGIN generated by tools/sync_engine_service_types.rb"
END_MARKER = "# END generated by tools/sync_engine_service_types.rb"

options = { engine: ENV["RUFLET_ENGINE_ROOT"] || File.expand_path("../ruflet-engine", ROOT), check: false }
OptionParser.new do |parser|
  parser.on("--engine PATH") { |path| options[:engine] = File.expand_path(path) }
  parser.on("--check") { options[:check] = true }
end.parse!

# Returns the body of every `createService(...) { ... }` method in +source+.
def create_service_bodies(source)
  bodies = []
  offset = 0
  while (start = source.index(/\bcreateService\s*\(/, offset))
    open = source.index("{", source.index(")", start))
    depth = 0
    index = open
    while index < source.length
      depth += 1 if source[index] == "{"
      depth -= 1 if source[index] == "}"
      break if depth.zero?

      index += 1
    end
    bodies << source[open..index]
    offset = index + 1
  end
  bodies
end

def engine_service_types(engine)
  packages = Dir.glob(File.join(engine, "packages", "ruflet{,_*}", "lib", "**", "*.dart"))
  raise "no engine packages under #{engine}" if packages.empty?

  packages.sort.flat_map do |path|
    create_service_bodies(File.read(path, encoding: "UTF-8")).flat_map { |body| body.scan(/case\s+"([A-Za-z0-9_]+)"\s*:/).flatten }
  end.uniq.sort
end

types = engine_service_types(options[:engine])
raise "found no createService registrations under #{options[:engine]}" if types.empty?

lines = types.each_slice(6).map { |slice| "        #{slice.join(' ')}" }
generated = [
  "      #{BEGIN_MARKER}",
  "      ENGINE_SERVICE_TYPES = %w[",
  *lines,
  "      ].each_with_object({}) { |wire, types| types[wire] = true }.freeze",
  "      #{END_MARKER}"
].join("\n")

current = File.read(TARGET, encoding: "UTF-8")
pattern = /^ *#{Regexp.escape(BEGIN_MARKER)}\n.*?^ *#{Regexp.escape(END_MARKER)}/m
raise "markers not found in #{TARGET}" unless current.match?(pattern)

updated = current.sub(pattern, generated)
if options[:check]
  if updated == current
    puts "ENGINE_SERVICE_TYPES is current (#{types.length} service types)"
  else
    warn "ENGINE_SERVICE_TYPES is stale; run tools/sync_engine_service_types.rb --engine #{options[:engine]}"
    exit 1
  end
else
  File.write(TARGET, updated)
  puts "wrote #{types.length} service types: #{types.join(', ')}"
end
