# frozen_string_literal: true

module Ruflet
  module UI
    # The wire types the Flutter engine registers as services (`createService`
    # in packages/ruflet and every packages/ruflet_* extension), not as widgets
    # (`createWidget`). The client mounts these in the page's service registry;
    # they never render in a layout. Camera is registered with `createWidget`,
    # so it is not listed even though Ruby keeps it in RufletServices.
    #
    # The list between the markers is generated from the engine sources by
    # `ruby tools/sync_engine_service_types.rb --engine <ruflet-engine>`; run it
    # with `--check` to verify it after an engine update. Do not edit by hand.
    module ServiceTypes
      # BEGIN generated by tools/sync_engine_service_types.rb
      ENGINE_SERVICE_TYPES = %w[
        Accelerometer Audio AudioRecorder Barometer Battery BrowserContextMenu
        Clipboard Connectivity FilePicker Flashlight Geolocator Gyroscope
        HapticFeedback InterstitialAd Magnetometer PermissionHandler ScreenBrightness SecureStorage
        SemanticsService ShakeDetector Share SharedPreferences StoragePaths Tester
        UrlLauncher UserAccelerometer Wakelock Window
      ].each_with_object({}) { |wire, types| types[wire] = true }.freeze
      # END generated by tools/sync_engine_service_types.rb

      module_function

      def service_wire_type?(wire)
        ENGINE_SERVICE_TYPES.key?(wire.to_s)
      end

      # Whether a Ruby DSL name (`audio`, `audio_recorder`, `interstitialad`)
      # builds a control the engine treats as a service.
      def service_name?(name)
        key = name.to_s.downcase
        klass = ControlFactory::EXTENSION_CLASS_MAP[key] || ControlFactory::CLASS_MAP[key] ||
                ControlFactory::CLASS_MAP[key.delete("_")]
        return false unless klass && klass.const_defined?(:WIRE)

        service_wire_type?(klass::WIRE)
      end
    end
  end
end
